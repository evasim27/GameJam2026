"""Copy playable ending art and regenerate GDScript data from the source manifests.

Run: python3 game/tools/import_ending_cutscenes.py
The original all-three group is used only by Exchange, never by incomplete Rewind outcomes.
"""

import json
from pathlib import Path
import shutil

PROJECT = Path(__file__).resolve().parents[2]
SOURCE = PROJECT / "assets/cutscenes"
GAME = PROJECT / "game"
DESTINATION = GAME / "assets/ending/cutscenes"
NAMES = ["Maja 1994", "Luka 1989", "Tina 2003"]


def main():
    index_path = SOURCE / "ending_rewind/variants/index.json"
    index = json.loads(index_path.read_text())
    assert index["selection"]["rewind_masks"] == list(range(7))
    assert index["selection"]["exchange_mask"] == 7
    copied = set()

    def sequence(manifest_path):
        manifest = json.loads(manifest_path.read_text())
        frames = []
        for frame in manifest["frames"]:
            source = (manifest_path.parent / frame["file"]).resolve()
            relative = source.relative_to(SOURCE)
            target = DESTINATION / relative
            assert source.is_file(), source
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(source, target)
            copied.add(relative)
            frames.append({
                "image": "res://" + target.relative_to(GAME).as_posix(),
                "caption": frame["caption"],
            })
        return frames

    rewind = [None] * 7
    for variant in index["variants"]:
        path = index_path.parent / variant["manifest"]
        manifest = json.loads(path.read_text())
        mask = variant["rescue_mask"]
        assert manifest["rescued"] == [name for i, name in enumerate(NAMES) if mask & (1 << i)]
        rewind[mask] = sequence(path)
    assert all(rewind)
    exchange = sequence(SOURCE / "ending_exchange/manifest.json")
    script = "extends RefCounted\n## Generated by tools/import_ending_cutscenes.py. Do not edit by hand.\n"
    for name, value in [("NAMES", NAMES), ("REWIND", rewind), ("EXCHANGE", exchange)]:
        script += "\nconst " + name + " := " + json.dumps(value, indent="\t") + "\n"
    (GAME / "rewind/ending_sequences.gd").write_text(script)
    print(f"Imported {len(copied)} unique images; generated 7 Rewind sequences and Menjava.")


if __name__ == "__main__":
    main()
